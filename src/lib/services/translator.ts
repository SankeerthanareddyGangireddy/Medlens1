export async function translateMedicalText(
  text: string,
  targetLang: SupportedLanguage
): Promise<string> {
  if (!text || targetLang === "en") return text;

  // 1. Try OpenAI if API key exists
  const apiKey = process.env.OPENAI_API_KEY;
  if (apiKey) {
    try {
      const langName = targetLang === "hi" ? "Hindi" : "Telugu";
      const res = await fetch(`${(process.env.OPENAI_BASE_URL || "https://api.openai.com/v1").replace(/\/$/, "")}/chat/completions`, {
        method: "POST",
        headers: {
          Authorization: `Bearer ${apiKey}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          model: process.env.OPENAI_MODEL || "gpt-4o-mini",
          temperature: 0.1,
          messages: [
            {
              role: "system",
              content: `You are a certified clinical translator specializing in medical reports. Translate the provided medical summary accurately into ${langName}. Preserve lab values, units, and drug names with clarity in the target script. Do not give any medical advice.`,
            },
            {
              role: "user",
              content: text,
            },
          ],
        }),
      });

      if (res.ok) {
        const data = await res.json();
        const translated = data.choices?.[0]?.message?.content;
        if (translated) return translated.trim();
      }
    } catch (e) {
      console.warn("OpenAI translation fallback activated:", e);
    }
  }

  // 2. High-Fidelity Rule-Based Medical Translation for Telugu & Hindi
  return generateMedicalTranslationFallback(text, targetLang);
}

